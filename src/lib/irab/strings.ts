export const STRINGS = { ar, en };
export type Strings = typeof ar;

/** Arabic-Indic digits in Arabic, Western in English. */
export function digits(n: number | string, lang: Lang): string {
  const s = String(n);
  if (lang === 'en') return s;
  return s.replace(/[0-9]/g, (d) => '٠١٢٣٤٥٦٧٨٩'[Number(d)]);
}

export function ago(ts: number, s: Strings): string {
  const mins = Math.max(0, Math.round((Date.now() - ts) / 60000));
  if (mins < 1) return s.ago.now;
  if (mins < 60) return s.ago.minutes(mins);
  const hours = Math.round(mins / 60);
  if (hours < 24) return s.ago.hours(hours);
  const days = Math.round(hours / 24);
  return days === 1 ? s.ago.yesterday : s.ago.days(days);
}
